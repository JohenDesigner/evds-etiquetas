// ÍCONES próprios, em grade 24x24. p = traços (listas de pontos); c = círculos [x,y,raio]; f = círculos cheios.
(function (g) {
  const arco = (cx, cy, r, a, b, n = 18) => Array.from({ length: n + 1 }, (_, i) => {
    const t = (a + (b - a) * i / n) * Math.PI / 180;
    return [cx + r * Math.cos(t), cy + r * Math.sin(t)];
  });
  const ret = (x, y, w, h) => [[x, y], [x + w, y], [x + w, y + h], [x, y + h], [x, y]];
  const onda = (y, x0, x1) => Array.from({ length: 25 }, (_, i) => [x0 + (x1 - x0) * i / 24, y + 1.4 * Math.sin(i / 24 * Math.PI * 4)]);
  const I = {
    power: { p: [arco(12, 13, 8, -55, 235), [[12, 3], [12, 12]]] },
    dr: { p: [ret(3, 3, 18, 18), [[13, 6], [8, 13], [12, 13], [11, 18], [16, 11], [12, 11], [13, 6]]] },
    raio: { p: [[[14, 2], [5, 14], [11, 14], [10, 22], [19, 10], [13, 10], [14, 2]]] },
    luz: { p: [arco(12, 9.5, 6.5, 125, 415), [[8.3, 14.8], [9, 18], [15, 18], [15.7, 14.8]], [[10, 21.5], [14, 21.5]]] },
    tomada: { c: [[12, 12, 9.5]], f: [[8, 11, 1.5], [16, 11, 1.5], [12, 15.5, 1.5]] },
    chuveiro: { p: [[[12, 2], [12, 6]], arco(12, 13, 7, 180, 360), [[4, 13], [20, 13]], [[7, 16], [6.5, 18]], [[12, 16], [12, 18]], [[17, 16], [17.5, 18]], [[9.5, 19.5], [9.2, 21.5]], [[14.5, 19.5], [14.8, 21.5]]] },
    torneira: { p: [[[3, 9], [14, 9], [18, 13], [18, 16], [14, 16], [14, 14], [3, 14], [3, 9]], [[9, 9], [9, 4]], [[5, 4], [13, 4]], [[16, 19], [16, 21.5]]] },
    ar: { p: [ret(2, 4, 20, 8), [[5, 9], [19, 9]], [[7, 15], [6, 19]], [[12, 15], [12, 20]], [[17, 15], [18, 19]]] },
    micro: { p: [ret(2, 5, 20, 14), ret(5, 8, 9, 8)], f: [[18, 9, 1.2], [18, 12.5, 1.2], [18, 16, 1.2]] },
    forno: { p: [ret(3, 3, 18, 18), [[3, 8.5], [21, 8.5]], ret(6.5, 11.5, 11, 6.5)], f: [[8, 5.8, 1], [12, 5.8, 1], [16, 5.8, 1]] },
    geladeira: { p: [ret(5, 2, 14, 20), [[5, 9], [19, 9]], [[8.5, 5], [8.5, 7]], [[8.5, 12], [8.5, 16]]] },
    lavar: { p: [ret(3, 2, 18, 20), [[3, 7], [21, 7]], onda(15, 8.5, 15.5)], c: [[12, 14.5, 5]], f: [[6.5, 4.5, 1]] },
    motor: { p: [[[8, 16], [8, 8.5], [12, 13], [16, 8.5], [16, 16]]], c: [[12, 12, 9.5]] },
    portao: { p: [ret(3, 4, 18, 17), [[3, 9], [21, 9]], [[3, 13], [21, 13]], [[3, 17], [21, 17]]] },
    carro: { p: [[[2, 17], [2, 12], [5, 11], [7.5, 6], [16.5, 6], [19, 11], [22, 12], [22, 17], [2, 17]], [[5, 11], [19, 11]]], c: [[7, 18, 2.2], [17, 18, 2.2]] },
    tela: { p: [ret(2, 4, 20, 13), [[12, 17], [12, 21]], [[7, 21], [17, 21]]] },
    reserva: { p: [[[12, 6], [12, 18]], [[6, 12], [18, 12]]], c: [[12, 12, 9.5]] }
  };
  function svg(nome, cor = 'currentColor', attrs = '') {
    const i = I[nome] || I.raio, r = v => +v.toFixed(2);
    return `<svg viewBox="0 0 24 24" fill="none" stroke="${cor}" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" ${attrs}>` +
      (i.p || []).map(p => `<polyline points="${p.map(q => r(q[0]) + ',' + r(q[1])).join(' ')}"/>`).join('') +
      (i.c || []).map(c => `<circle cx="${c[0]}" cy="${c[1]}" r="${c[2]}"/>`).join('') +
      (i.f || []).map(c => `<circle cx="${c[0]}" cy="${c[1]}" r="${c[2]}" fill="${cor}" stroke="none"/>`).join('') + '</svg>';
  }
  g.Icones = { I, svg };
})(globalThis);
